-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.community_games (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 40),
  description text not null default '' check (char_length(description) <= 180),
  tiles jsonb not null,
  created_at timestamptz not null default now()
);

alter table public.community_games enable row level security;
-- Anyone can read published community levels.
create policy "Anyone can view community games"
  on public.community_games for select to anon, authenticated using (true);
-- Public uploads are allowed for this demo site. Add auth/moderation and rate limits before treating it as production.
drop policy if exists "Anyone can publish community games" on public.community_games;
create policy "Anyone can publish community games"
  on public.community_games for insert to anon, authenticated with check (
    char_length(name) between 1 and 40
    and char_length(description) <= 180
    and jsonb_typeof(tiles) = 'array'
    and jsonb_array_length(tiles) = 240
  );

 
-- Shared SMOKE community discussions.
create table if not exists public.community_posts (
  id bigint generated by default as identity primary key,
  display_name text not null check (char_length(display_name) between 1 and 24),
  category text not null default 'General Discussion'
    check (category in ('General Discussion','Help & Tips','Game Suggestions','Off Topic','SMOKE Workshop')),
  title text not null check (char_length(title) between 1 and 90),
  body text not null check (char_length(body) between 1 and 1200),
  created_at timestamptz not null default now()
);

alter table public.community_posts enable row level security;
drop policy if exists "Anyone can view community posts" on public.community_posts;
create policy "Anyone can view community posts"
  on public.community_posts for select to anon, authenticated using (true);
drop policy if exists "Anyone can create community posts" on public.community_posts;
create policy "Anyone can create community posts"
  on public.community_posts for insert to anon, authenticated with check (
    char_length(display_name) between 1 and 24
    and category in ('General Discussion','Help & Tips','Game Suggestions','Off Topic','SMOKE Workshop')
    and char_length(title) between 1 and 90
    and char_length(body) between 1 and 1200
  );
